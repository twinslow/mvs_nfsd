/*
 * ebcdic.c - IBM Code Page 037 (CP037) EBCDIC <-> ASCII translation.
 *
 * CP037 is the EBCDIC code page used by MVS 3.8j (US/Canada variant).
 *
 * TRANSLATION TABLE NOTES
 * -----------------------
 * The 256-entry tables below were derived from the IBM CP037 definition.
 *
 * ebcdic_to_ascii_tab[e] = a  means EBCDIC byte e -> ASCII byte a.
 * ascii_to_ebcdic_tab[a] = e  means ASCII  byte a -> EBCDIC byte e.
 *
 * Bytes with no natural mapping:
 *   EBCDIC -> ASCII: unmapped control chars -> 0x1A (ASCII SUB / '?')
 *   ASCII  -> EBCDIC: unmapped chars above 0x7E -> EBCDIC 0x3F ('?')
 *
 * KEY CONTROL CHARACTERS
 *   EBCDIC 0x15 (NL)  <-> ASCII 0x0A (LF)
 *   EBCDIC 0x25 (LF)  <-> ASCII 0x0A (LF)  [same target; 0x15 preferred]
 *   EBCDIC 0x0D (CR)  <-> ASCII 0x0D (CR)
 *   EBCDIC 0x05 (HT)  <-> ASCII 0x09 (TAB)
 *   EBCDIC 0x40 (SP)  <-> ASCII 0x20 (SP)
 *   EBCDIC 0xFF (EO)  ->  ASCII 0xFF         [pass-through]
 *
 * MVS PDS MEMBER NAMES
 *   Member names are 1-8 chars: A-Z (0-9 after first), @, #, $.
 *   They are stored in EBCDIC in the PDS directory, space-padded to 8.
 *   Use ebcdic_member_to_name() / name_to_ebcdic_member() for these.
 *
 * RECORD HANDLING (for vfs_mvs.c)
 *   Fixed-length records (RECFM=F, LRECL=nn):
 *     Read: strip trailing EBCDIC spaces (0x40), translate to ASCII,
 *           append ASCII LF (0x0A).
 *     Write: remove trailing ASCII LF, translate to EBCDIC,
 *            pad with EBCDIC spaces (0x40) to LRECL.
 *
 *   Variable-length records (RECFM=V):
 *     Each block has a 4-byte BDW + records each with 4-byte RDW.
 *     Strip the 4-byte RDW, translate data, append LF on read.
 */

