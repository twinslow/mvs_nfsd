/*
 * ebcdic_to_ascii: translate 'len' EBCDIC bytes from src into dst.
 * In-place translation is safe (dst == src allowed).
 */
void ebcdic_to_ascii(uint8_t *dst, const uint8_t *src, size_t len)
{
    size_t i;
    for (i = 0; i < len; i++)
        dst[i] = ebcdic_to_ascii_tab[src[i]];
}

/*
 * ascii_to_ebcdic: translate 'len' ASCII bytes from src into dst.
 */
void ascii_to_ebcdic(uint8_t *dst, const uint8_t *src, size_t len)
{
    size_t i;
    for (i = 0; i < len; i++)
        dst[i] = ascii_to_ebcdic_tab[src[i]];
}

