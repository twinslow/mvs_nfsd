/* PDS member name utilities                                            */
/* ==================================================================== */

/*
 * ebcdic_member_to_name: convert an 8-byte EBCDIC PDS member name
 * (stored in DIRECTORY block, space-padded) to a NUL-terminated
 * ASCII filename.
 *
 * MVS member names: A-Z, 0-9, @, #, $ (first char must be A-Z/@/#/$).
 * After conversion to ASCII these map identically (all are in the
 * common ASCII/EBCDIC subset).
 *
 * Trailing EBCDIC spaces (0x40) are stripped.
 * dst must be at least 9 bytes.
 * Returns length of the resulting string (0-8).
 */
int ebcdic_member_to_name(char *dst, const uint8_t *member8)
{
    int len = 8;
    int i;

    /* Strip trailing EBCDIC spaces */
    while (len > 0 && member8[len - 1] == 0x40)
        len--;

    for (i = 0; i < len; i++)
        dst[i] = (char)ebcdic_to_ascii_tab[member8[i]];
    dst[len] = '\0';
    return len;
}

/*
 * name_to_ebcdic_member: convert a NUL-terminated ASCII filename to
 * an 8-byte EBCDIC PDS member name (upper-cased, space-padded to 8).
 *
 * Valid member name characters (ASCII): A-Z, a-z (upper-cased), 0-9,
 * @, #, $.  Length must be 1-8.
 *
 * Returns 0 if the name is valid, -1 if too long or contains an
 * invalid character.
 */
int name_to_ebcdic_member(uint8_t *member8, const char *name)
{
    static const char valid[] =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789@#$";
    size_t len = strlen(name);
    size_t i;
    char   uc;

    if (len == 0 || len > 8) return -1;

    for (i = 0; i < len; i++) {
        uc = (char)toupper((unsigned char)name[i]);
        if (!strchr(valid, uc)) return -1;
        member8[i] = ascii_to_ebcdic_tab[(unsigned char)uc];
    }

    /* Pad remainder with EBCDIC space (0x40) */
    for (i = len; i < 8; i++)
        member8[i] = 0x40;

    return 0;
}

